import 'dart:typed_data';

import 'mandataire.dart';

class User {
  const User({
    required this.id,
    required this.lastName,
    required this.postName,
    required this.firstName,
    required this.email,
    required this.dateOfBirth,
    required this.identityNumber,
    required this.profilePhotoPath,
    this.phoneNumber = '',
    this.city = '',
    this.commune = '',
    this.neighborhood = '',
    this.cell = '',
    this.houseNumber = '',
    this.profilePhotoBytes,
    this.identityDocumentPages = const [],
    required this.passwordHash,
    required this.mandataire,
  });

  final String id;
  final String lastName;
  final String postName;
  final String firstName;
  final String email;
  final DateTime dateOfBirth;
  final String identityNumber;
  final String profilePhotoPath;
  final String phoneNumber;
  final String city;
  final String commune;
  final String neighborhood;
  final String cell;
  final String houseNumber;
  final Uint8List? profilePhotoBytes;
  final List<Uint8List> identityDocumentPages;

  /// Must be generated by a server-side password hasher; never store raw passwords.
  final String passwordHash;

  final Mandataire mandataire;

  String get fullName => '$firstName $postName $lastName'.trim();
}
